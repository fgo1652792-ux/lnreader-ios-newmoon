// Pure-TypeScript SHA-256 (hex). Hermes has no SubtleCrypto and Zeus used
// CryptoKit SHA256 for TranslationMemory keys — this is the drop-in equivalent,
// deterministic across Hermes/node so unit tests can verify key derivation.
// Standard FIPS 180-4 implementation over UTF-8 bytes.

