const utf8Bytes = (input: string): Uint8Array => {
  // encodeURIComponent-based UTF-8 encoding. Note: lone surrogates encode as
  // U+FFFD, matching Swift's lossy String->Data(utf8) behaviour.
  const escaped = encodeURIComponent(input);
  const bytes = new Uint8Array(escaped.length);
  let n = 0;
  for (let i = 0; i < escaped.length; i += 1) {
    if (escaped[i] === '%') {
      bytes[n] = parseInt(escaped.slice(i + 1, i + 3), 16);
      i += 2;
    } else {
      bytes[n] = escaped.charCodeAt(i);
    }
    n += 1;
  }
  return bytes.subarray(0, n);
};

export const sha256Hex = (input: string): string => {
  const message = utf8Bytes(input);
  const bitLength = message.length * 8;
  const blockCount = ((message.length + 8) >> 6) + 1;
  const words = new Uint32Array(blockCount * 16);
  for (let i = 0; i < message.length; i += 1) {
    words[i >> 2] |= message[i] << (24 - (i % 4) * 8);
  }
  words[message.length >> 2] |= 0x80 << (24 - (message.length % 4) * 8);
  words[blockCount * 16 - 1] = bitLength >>> 0;
  words[blockCount * 16 - 2] = Math.floor(bitLength / 0x100000000);

  const w = new Uint32Array(64);
  let h0 = 0x6a09e667;
  let h1 = 0xbb67ae85;
  let h2 = 0x3c6ef372;
  let h3 = 0xa54ff53a;
  let h4 = 0x510e527f;
  let h5 = 0x9b05688c;
  let h6 = 0x1f83d9ab;
  let h7 = 0x5be0cd19;

  for (let block = 0; block < blockCount; block += 1) {
    const base = block * 16;
    for (let i = 0; i < 16; i += 1) w[i] = words[base + i];
    for (let i = 16; i < 64; i += 1) {
      const s0 =
        ((w[i - 15] >>> 7) | (w[i - 15] << 25)) ^
        ((w[i - 15] >>> 18) | (w[i - 15] << 14)) ^
        (w[i - 15] >>> 3);
      const s1 =
        ((w[i - 2] >>> 17) | (w[i - 2] << 15)) ^
        ((w[i - 2] >>> 19) | (w[i - 2] << 13)) ^
        (w[i - 2] >>> 10);
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) >>> 0;
    }
    let a = h0;
    let b = h1;
    let c = h2;
    let d = h3;
    let e = h4;
    let f = h5;
    let g = h6;
    let h = h7;
    for (let i = 0; i < 64; i += 1) {
      const S1 = ((e >>> 6) | (e << 26)) ^ ((e >>> 11) | (e << 21)) ^ ((e >>> 25) | (e << 7));
      const ch = (e & f) ^ (~e & g);
      const temp1 = (h + S1 + ch + K[i] + w[i]) >>> 0;
      const S0 = ((a >>> 2) | (a << 30)) ^ ((a >>> 13) | (a << 19)) ^ ((a >>> 22) | (a << 10));
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const temp2 = (S0 + maj) >>> 0;
      h = g;
      g = f;
      f = e;
      e = (d + temp1) >>> 0;
      d = c;
      c = b;
      b = a;
      a = (temp1 + temp2) >>> 0;
    }
    h0 = (h0 + a) >>> 0;
    h1 = (h1 + b) >>> 0;
    h2 = (h2 + c) >>> 0;
    h3 = (h3 + d) >>> 0;
    h4 = (h4 + e) >>> 0;
    h5 = (h5 + f) >>> 0;
    h6 = (h6 + g) >>> 0;
    h7 = (h7 + h) >>> 0;
  }

  return [h0, h1, h2, h3, h4, h5, h6, h7]
    .map(value => value.toString(16).padStart(8, '0'))
    .join('');
};
